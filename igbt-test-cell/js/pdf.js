/* Client-side, vector PDF export. Uses the same report object and display helpers as the HTML report.
   No upload, model call or server is involved in creating or sharing this file. */
window.IGBT = window.IGBT || {};
window.IGBT.pdf = (function () {
  function create(report, opts) {
    opts = opts || {};
    if (!window.jspdf || !window.IGBT_PDF_FONT) throw new Error('PDF exporter could not load. Use Save PDF instead.');
    var R = window.IGBT.report, T = R.text, det = report.deterministic, md = report.metadata;
    var ss = det.safe_state, inp = det.inputs, ai = opts.ai;
    var doc = new window.jspdf.jsPDF({ unit: 'mm', format: 'a4', compress: true, putOnlyUsedFonts: true });
    doc.addFileToVFS('NotoSans.ttf', window.IGBT_PDF_FONT);
    doc.addFont('NotoSans.ttf', 'NotoSans', 'normal');
    doc.setFont('NotoSans', 'normal');
    doc.setProperties({ title: 'IGBT Test Cell report ' + (md.run_id || ''), subject: 'Test results and AI analysis' });
    var y = 18, left = 14, width = 182, bottom = 280;
    function clean(value) { return String(value == null ? '' : value).replace(/[\u2010-\u2015\u2212]/g, '-'); }
    function room(height) { if (y + height > bottom) { doc.addPage(); y = 18; } }
    function paragraph(value, size, gap, color) {
      doc.setFontSize(size || 9); doc.setTextColor(color || 35);
      var lines = doc.splitTextToSize(clean(value), width);
      lines.forEach(function (line) { room(4.3); doc.text(line, left, y); y += 4.3; });
      y += gap == null ? 2 : gap;
    }
    function heading(value) {
      room(16); y += 3; paragraph(value, 12, 2);
      doc.setDrawColor(180); doc.setLineWidth(0.2); doc.line(left, y - 1, left + width, y - 1); y += 4;
    }
    paragraph('IGBT Test Cell - test report', 18, 5);
    [
      'Report: ' + (md.run_id || '-'), 'Module: ' + inp.module_parameters.module_id,
      'Operator: ' + (md.operator || '-'), 'Date: ' + md.created_local,
      'Version: v' + md.software_version + ' · schema ' + report.schema_version
    ].forEach(function (line) { paragraph(line, 8, 0, 85); });
    y += 4; heading('A. Test results');
    paragraph(T.outcomeKind(det).title, 13, 2);
    paragraph(det.overall.precedence_reason + '.', 9, 2);
    var bench = ss ? 'Final state ' + T.statusText(ss.final_state) + ' · ' + T.verificationText(ss) +
      (ss.verification === 'VERIFICATION_UNAVAILABLE' ? ' · bus ' + T.vBusVerifyText(ss) : '') + ' · enclosure door ' + ss.door
      : 'Safe-state procedure not run';
    paragraph(bench, 8, 3, 75);
    paragraph('Key findings', 10, 1);
    var findings = T.keyFindings(det);
    if (!findings.length) paragraph('None. Every evaluated reading is within its reference range.', 8, 2);
    findings.forEach(function (finding) { paragraph('• ' + finding.text, 8, 1); });
    y += 2; room(20);
    var rows = [];
    det.stages.forEach(function (stage) {
      rows.push([{ content: clean(stage.test_id + ' ' + stage.name + ' · ' + T.statusText(stage.status) +
        (stage.blocked_reason ? ' - ' + stage.blocked_reason : '')), colSpan: 4,
        styles: { fillColor: [241, 241, 241], textColor: 30, cellPadding: 2.2 } }]);
      stage.readings.forEach(function (reading) {
        rows.push([clean(reading.quantity_id + ' ' + reading.label), clean(T.valueText(reading) +
          (T.unitOf(reading) ? ' ' + T.unitOf(reading) : '')), clean(T.ruleText(reading)), reading.verdict]);
      });
    });
    doc.autoTable({ startY: y, margin: { top: 16, bottom: 18, left: left, right: left },
      head: [['Test', 'Reading', 'Reference range', 'Result']], body: rows, theme: 'plain',
      styles: { font: 'NotoSans', fontStyle: 'normal', fontSize: 7.5, cellPadding: 2,
        textColor: 35, lineColor: 225, lineWidth: { bottom: 0.1 }, overflow: 'linebreak' },
      headStyles: { fontStyle: 'normal', fillColor: [226, 226, 226], textColor: 30 },
      columnStyles: { 0: { cellWidth: 83 }, 1: { cellWidth: 25 }, 2: { cellWidth: 48 }, 3: { cellWidth: 26 } },
      rowPageBreak: 'avoid' });
    y = doc.lastAutoTable.finalY + 7;
    var counts = T.countsText(det);
    paragraph(counts.readings + ' · ' + counts.stages, 7.5, 1, 90);
    paragraph('Run configuration: preset ' + inp.scenario_id + ' · seed ' + inp.seed +
      (T.overridesText(inp) !== 'none (defaults)' ? ' · changed inputs: ' + T.overridesText(inp) : ''), 7.5, 3, 90);
    room(ai ? 58 : 23); heading('B. AI analysis');
    if (ai) {
      paragraph('Generated by ' + ai.model + ' · ' + ai.generated_local + ' · recorded results unchanged.', 7.5, 3, 90);
      paragraph(ai.summary, 9, 3);
      (ai.items || []).forEach(function (item) {
        var value = typeof item.value === 'string' ? item.value : JSON.stringify(item.value);
        paragraph('• ' + item.explanation + ' (' + (item.label || 'recorded value') + ': ' + value +
          (item.unit ? ' ' + item.unit : '') + ')', 8, 2);
      });
      paragraph('Bench status (recorded, not generated): ' + bench + '.', 7.5, 2, 85);
    } else paragraph('No AI analysis was generated for this run.', 9, 2, 90);
    var pages = doc.getNumberOfPages();
    for (var page = 1; page <= pages; page++) {
      doc.setPage(page); doc.setFontSize(7); doc.setTextColor(110);
      doc.text(clean(md.run_id || 'IGBT Test Cell'), left, 289);
      doc.text(page + ' / ' + pages, 196, 289, { align: 'right' });
    }
    return { blob: doc.output('blob'), name: R.fileName(report, 'pdf').replace(/[\\/:*?"<>|]/g, '_') };
  }
  function download(file) {
    var url = URL.createObjectURL(file), link = document.createElement('a');
    link.href = url; link.download = file.name; document.body.appendChild(link); link.click(); link.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 60000);
  }
  function shareFile(file, env) {
    env = env || {}; var nav = env.navigator || navigator, save = env.download || download;
    var available = false;
    try { available = typeof nav.share === 'function' && typeof nav.canShare === 'function' && nav.canShare({ files: [file] }); }
    catch (e) { available = false; }
    if (!available) { save(file); return Promise.resolve('download'); }
    // Call share synchronously inside the click handler; do not lose user activation to an awaited render/upload.
    try {
      return Promise.resolve(nav.share({ files: [file], title: 'IGBT Test Cell report' })).then(function () { return 'share'; },
        function (error) { if (error && error.name === 'AbortError') return 'cancelled'; save(file); return 'download'; });
    } catch (error) {
      if (error && error.name === 'AbortError') return Promise.resolve('cancelled');
      save(file); return Promise.resolve('download');
    }
  }
  return { create: create, shareFile: shareFile };
})();
